// Keep the ES5 standalone early script and embedded normalizer in sync with TS.
import ts from 'typescript';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const read = (path) => readFileSync(new URL(path, root), 'utf8');
const compile = (source) => ts.transpileModule(source, {
  compilerOptions: { target: ts.ScriptTarget.ES5, module: ts.ModuleKind.ESNext },
}).outputText.replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const normalizer = read('src/utils/errorEvidence.ts').split('const identities =')[0];
const code = compile(normalizer);
const expression = `(function () {\n${code}\nreturn normalizeErrorEvidence;\n})()`;
const module = '// Generated by scripts/generate-error-capture.mjs; do not edit.\n' +
  `export const errorEvidenceSource = ${JSON.stringify(expression)};\n`;
const early = compile(read('src/build-plugins/early-error-script.ts'));
const generate = new Function('errorEvidenceSource', early + '\nreturn getEarlyErrorCaptureScript;')(expression);
const standalone = '// Generated by scripts/generate-error-capture.mjs; do not edit.\n' + generate({ autoRefreshOnChunkError: false, checkCompatibility: false }) + '\n';
for (const [path, value] of [
  ['src/build-plugins/error-evidence.generated.ts', module],
  ['scripts/early-error.js', standalone],
]) {
  if (process.argv.includes('--check')) {
    if (read(path) !== value) throw new Error('Stale generated file: ' + path);
  } else writeFileSync(fileURLToPath(new URL(path, root)), value);
}
